#!/usr/bin/env python3
"""Decode actual unscoped CPC fixtures into data for kernel-checked replay.

No rule computes in Python. Every step (including unused steps) is sent to
CpcGenerated.derive in Rocq. Unsupported commands and dangling IDs reject here.
"""
import argparse
import hashlib
from pathlib import Path
from compile import parse, atom, seq, quoted, lst, apply_ir, SignatureError


def decode(path):
    forms = parse(path.read_text(), path)
    if atom(forms[0]) != 'unsat' or len(forms) != 2:
        raise SignatureError('expected unsat followed by one proof block')
    aliases, decls, roots, steps, ids = {}, [], [], [], set()

    def term(n):
        if n.kind == 'symbol':
            return aliases.get(atom(n), f'(Symbol {quoted(atom(n))})')
        fs = seq(n)
        if not fs:
            n.error('empty term')
        if atom(fs[0]) == '->' and len(fs) > 3:
            # Function types use nested binary arrows in the public query API.
            result = term(fs[-1])
            for a in reversed(fs[1:-1]):
                result = f'(arrow {term(a)} {result})'
            return result
        return apply_ir(term(fs[0]), [term(a) for a in fs[1:]], 'Apply')

    def ident(n):
        name = atom(n)
        if not name.startswith('@p') or not name[2:].isdigit():
            n.error('expected numbered proof ID')
        return int(name[2:])

    for command in seq(forms[1]):
        fs = seq(command)
        cmd = atom(fs[0])
        if cmd == 'declare-sort':
            if len(fs) != 3 or atom(fs[2]) != '0':
                command.error('only nullary fixture sorts supported')
        elif cmd == 'declare-const':
            decls.append(f'({quoted(atom(fs[1]))}, {term(fs[2])})')
        elif cmd == 'define':
            if seq(fs[2]):
                command.error('fixture definitions must be nullary')
            if atom(fs[1]) in aliases:
                command.error('duplicate definition')
            aliases[atom(fs[1])] = term(fs[3])
        elif cmd in {'assume', 'step'}:
            dest = ident(fs[1])
            if dest in ids:
                command.error('duplicate proof ID')
            if cmd == 'assume':
                roots.append(f'({dest}, {term(fs[2])})')
            else:
                i, declared = 2, 'None'
                if fs[i].kind != 'symbol' or not atom(fs[i]).startswith(':'):
                    declared = f'(Some {term(fs[i])})'
                    i += 1
                fields = {}
                while i < len(fs):
                    key = atom(fs[i])
                    if key not in {':rule', ':premises', ':args'} or key in fields:
                        fs[i].error('unsupported/duplicate step field')
                    fields[key] = fs[i+1]
                    i += 2
                premises = [ident(n) for n in seq(fields[':premises'])] if ':premises' in fields else []
                if any(p not in ids for p in premises):
                    command.error('missing/forward premise')
                args = [term(n) for n in seq(fields[':args'])] if ':args' in fields else []
                steps.append(f'{{| step_id := {dest}; step_rule := {quoted(atom(fields[":rule"]))}; step_args := {lst(args)}; step_premises := {lst(map(str,premises))}; step_declared := {declared} |}}')
            ids.add(dest)
        else:
            command.error(f'unsupported fixture command {cmd}; no steps may be skipped')
    return decls, roots, steps, dest


def generate(paths):
    code = ['(* Generated by replay_fixtures.py from actual CPC bytes. *)',
            'From Stdlib Require Import String List.',
            'From SMTCoq.checker.eunoia Require Import EoSyntax EoRuntime CpcGenerated TraceReplay.',
            'Import ListNotations.', 'Open Scope string_scope.']
    for path in paths:
        decls, roots, steps, goal = decode(path)
        name = path.stem.replace('-', '_')
        code += [f'(* {path.name}: sha256 {hashlib.sha256(path.read_bytes()).hexdigest()}, {len(steps)} steps. *)',
                 f'Definition {name}_decls : list (string * term) := {lst(decls)}.',
                 f'Definition {name}_roots : bindings := {lst(roots)}.',
                 f'Definition {name}_steps : list decoded_step := {lst(steps)}.',
                 f'Example {name}_all_steps : final_term (uf_query {name}_decls) {name}_roots {name}_steps {goal} = Some (Symbol "false").',
                 'Proof. vm_compute. reflexivity. Qed.',
                 f'Print Assumptions {name}_all_steps.']
    return '\n'.join(code) + '\n'


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('fixtures', nargs='+', type=Path)
    ap.add_argument('--output', required=True, type=Path)
    args = ap.parse_args()
    args.output.write_text(generate(args.fixtures))
