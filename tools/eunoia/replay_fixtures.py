#!/usr/bin/env python3
"""Decode actual CPC fixtures into data for kernel-checked replay.

No rule computes in Python. Every step (including unused steps) is sent to
CpcGenerated.derive/derive_assuming in Rocq. Unsupported commands and dangling IDs reject here.
"""
import argparse
import hashlib
from pathlib import Path
from compile import parse, atom, seq, quoted, lst, apply_ir, SignatureError


def decode(path, scoped=False):
    forms = parse(path.read_text(), path)
    if atom(forms[0]) != 'unsat' or len(forms) != 2:
        raise SignatureError('expected unsat followed by one proof block')
    aliases, decls, roots, steps, ids = {}, [], [], [], set()

    frames = []

    def term(n):
        if n.kind == 'symbol':
            return aliases.get(atom(n), f'(Symbol {quoted(atom(n))})')
        fs = seq(n)
        if not fs:
            n.error('empty term')
        if atom(fs[0]) == '->' and len(fs) > 3:
            # Function types use nested binary arrows in the public query API.
            result = term(fs[-1])
            for a in reversed(fs[1:-1]):
                result = f'(arrow {term(a)} {result})'
            return result
        return apply_ir(term(fs[0]), [term(a) for a in fs[1:]], 'Apply')

    def ident(n):
        name = atom(n)
        if not name.startswith('@p') or not name[2:].isdigit():
            n.error('expected numbered proof ID')
        return int(name[2:])

    for command in seq(forms[1]):
        fs = seq(command)
        cmd = atom(fs[0])
        if cmd == 'declare-sort':
            if len(fs) != 3 or atom(fs[2]) != '0':
                command.error('only nullary fixture sorts supported')
        elif cmd == 'declare-const':
            decls.append(f'({quoted(atom(fs[1]))}, {term(fs[2])})')
        elif cmd == 'define':
            if seq(fs[2]):
                command.error('fixture definitions must be nullary')
            if atom(fs[1]) in aliases:
                command.error('duplicate definition')
            aliases[atom(fs[1])] = term(fs[3])
        elif cmd in {'assume', 'step', 'assume-push', 'step-pop'}:
            if cmd in {'assume-push', 'step-pop'} and not scoped:
                command.error(f'unsupported fixture command {cmd}; scoped decoding required')
            dest = ident(fs[1])
            if cmd == 'step-pop':
                if not frames:
                    command.error('scope pop without push')
                available = frames[-1]
            else:
                available = ids
            if dest in available:
                command.error('duplicate proof ID')
            if cmd == 'assume':
                if frames:
                    command.error('root assumption inside local scope')
                roots.append(f'({dest}, {term(fs[2])})')
            elif cmd == 'assume-push':
                frames.append(ids.copy())
                steps.append(f'(TracePush {dest} {term(fs[2])})')
            else:
                i, declared = 2, 'None'
                if fs[i].kind != 'symbol' or not atom(fs[i]).startswith(':'):
                    declared = f'(Some {term(fs[i])})'
                    i += 1
                fields = {}
                while i < len(fs):
                    key = atom(fs[i])
                    if key not in {':rule', ':premises', ':args'} or key in fields:
                        fs[i].error('unsupported/duplicate step field')
                    fields[key] = fs[i+1]
                    i += 2
                premises = [ident(n) for n in seq(fields[':premises'])] if ':premises' in fields else []
                if any(p not in ids for p in premises):
                    command.error('missing/forward premise')
                args = [term(n) for n in seq(fields[':args'])] if ':args' in fields else []
                step = f'{{| step_id := {dest}; step_rule := {quoted(atom(fields[":rule"]))}; step_args := {lst(args)}; step_premises := {lst(map(str,premises))}; step_declared := {declared} |}}'
                steps.append(f'(TracePop {step})' if cmd == 'step-pop' else f'(TraceStep {step})' if scoped else step)
                if cmd == 'step-pop':
                    ids = frames.pop()
            ids.add(dest)
        else:
            command.error(f'unsupported fixture command {cmd}; no steps may be skipped')
    if frames:
        raise SignatureError('unclosed local scope')
    return decls, roots, steps, dest


def generate(paths, scoped=False):
    code = ['(* Generated by replay_fixtures.py from actual CPC bytes. *)',
            'From Stdlib Require Import String List.',
            'From SMTCoq.checker.eunoia Require Import EoSyntax EoRuntime CpcGenerated TraceReplay.',
            'Import ListNotations.', 'Open Scope string_scope.']
    if scoped:
        code.append('From SMTCoq.checker.eunoia Require Import LiaTraceReplay.')
    for path in paths:
        decls, roots, steps, goal = decode(path, scoped=scoped)
        name = path.stem.replace('-', '_')
        step_type = 'trace_command' if scoped else 'decoded_step'
        final = 'trace_final' if scoped else 'final_term'
        query = 'lia_query' if scoped else 'uf_query'
        code += [f'(* {path.name}: sha256 {hashlib.sha256(path.read_bytes()).hexdigest()}, {len(steps)} computation commands. *)',
                 f'Definition {name}_decls : list (string * term) := {lst(decls)}.',
                 f'Definition {name}_roots : bindings := {lst(roots)}.',
                 f'Definition {name}_steps : list {step_type} := {lst(steps)}.',
                 f'Example {name}_all_steps : {final} ({query} {name}_decls) {name}_roots {name}_steps {goal} = Some (Symbol "false").',
                 'Proof. vm_compute. reflexivity. Qed.',
                 f'Print Assumptions {name}_all_steps.']
    return '\n'.join(code) + '\n'


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('fixtures', nargs='+', type=Path)
    ap.add_argument('--scoped', action='store_true')
    ap.add_argument('--output', required=True, type=Path)
    args = ap.parse_args()
    args.output.write_text(generate(args.fixtures, scoped=args.scoped))
